#!/usr/bin/env node
// Copy the brand icon set into the web client as a generated React module.
//
// Source of truth: internal/icons/svg/*.svg (34 files, 16x16 grid / stroke 1.2
// plus a few 24x24 Lucide leftovers). Rule AGENTS.md §3.8 / WEB-CLIENT §9.5:
// business and navigation icons come from internal/icons — never emoji, never
// hand-written paths, never @ant-design/icons.
//
// The generated module keeps the SVG body as a string and renders it through
// one component. The bodies are static repository content (not user input), so
// `dangerouslySetInnerHTML` here is a build-time copy, not an injection point.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const sourceDir = resolve(repo, 'internal/icons/svg');

const files = readdirSync(sourceDir).filter((name) => name.endsWith('.svg')).sort();
if (files.length === 0) {
  console.error('gen-icons: no SVGs found in internal/icons/svg');
  process.exit(1);
}

const entries = [];
for (const file of files) {
  const name = file.replace(/\.svg$/, '');
  const svg = readFileSync(resolve(sourceDir, file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const strokeWidth = svg.match(/stroke-width="([^"]+)"/)?.[1];
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  if (!viewBox || !body) {
    console.error(`gen-icons: could not parse ${file}`);
    process.exit(1);
  }
  entries.push(
    `  ${JSON.stringify(name)}: { viewBox: ${JSON.stringify(viewBox)}, strokeWidth: ${JSON.stringify(
      strokeWidth ?? '1.2',
    )}, body: ${JSON.stringify(body)} },`,
  );
}

const out = `/* GENERATED by web/scripts/gen-icons.mjs — do not edit.
 *
 * Source: internal/icons/svg/*.svg (${files.length} icons). Regenerate: npm run gen:icons
 * Rule: business and navigation icons come from internal/icons, never from
 * emoji, hand-written paths or @ant-design/icons (AGENTS.md §3.8).
 */

export const ICONS = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof ICONS;

export const ICON_NAMES = Object.keys(ICONS) as IconName[];
`;

writeFileSync(resolve(repo, 'web/src/design/icons.tsx'), `${out}

import type { SVGProps } from 'react';

export interface ZkIconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  /** Pixel size; the design ladder is 16 / 20 / 24. */
  size?: number;
}

/**
 * One icon component for the whole client. Colour follows \`currentColor\`, so a
 * nav row, a status line and a button all tint it through the text token they
 * already use — no per-icon colour prop.
 */
export function ZkIcon({ name, size = 16, ...rest }: ZkIconProps) {
  const icon = ICONS[name];
  return (
    <svg
      width={size}
      height={size}
      viewBox={icon.viewBox}
      fill="none"
      stroke="currentColor"
      strokeWidth={icon.strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      // Static repository artwork (see the file header): copied verbatim at
      // build time so no icon geometry is re-authored in the browser bundle.
      dangerouslySetInnerHTML={{ __html: icon.body }}
      {...rest}
    />
  );
}
`);

console.log(`gen-icons: wrote web/src/design/icons.tsx (${files.length} icons)`);