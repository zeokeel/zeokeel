#!/usr/bin/env node
// Generate the WS contract constants from `internal/gateway/contract.json`.
//
// The gateway owns the wire contract (`params` per method, `capabilities.static`,
// `capabilities.conditional`). The client used to restate it by hand in three
// places — `dev/ws-params.mjs`, `src/test/fake-gateway.ts` and the mock's
// capability array — and every restatement was a place to drift. Two integration
// bugs came from exactly that (`prompts.enqueue`'s `prompt` field, and a
// capability list missing `approvals`).
//
// This copies the gateway's file into one generated module; nothing downstream
// may hand-write a method name or a capability again.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, '..');
const repoRoot = resolve(webRoot, '..');
/** Read a repo-relative file; `gen-baseline` parses exactly this shape. */
const read = (path) => readFileSync(resolve(repoRoot, path), 'utf8');

const CONTRACT = resolve(repoRoot, 'internal/gateway/contract.json');
const OUTPUT = resolve(webRoot, 'src/design/ws-contract.ts');

const raw = read('internal/gateway/contract.json');
let contract;
try {
  contract = JSON.parse(raw);
} catch (cause) {
  console.error(
    `gen-ws-contract: cannot parse ${CONTRACT}: ${cause.message}\n` +
      'If the file is missing or stale, regenerate it from the gateway: go generate ./internal/gateway',
  );
  process.exit(1);
}

const methods = Object.keys(contract.params).sort();
const lines = [];
lines.push('// Code generated by scripts/gen-ws-contract.mjs; DO NOT EDIT.');
lines.push('//');
lines.push('// Copied from internal/gateway/contract.json (the gateway owns the wire contract).');
lines.push('// If this file is missing or stale, run: go generate ./internal/gateway');
lines.push('//');
lines.push('/** Parameters the gateway accepts per method (`required` ⇒ no omitempty). */');
lines.push('export interface MethodParams {');
lines.push('  required: readonly string[];');
lines.push('  optional: readonly string[];');
lines.push('}');
lines.push('');
lines.push('export const WS_METHODS = [');
for (const method of methods) lines.push(`  '${method}',`);
lines.push('] as const;');
lines.push('');
lines.push('export type WsMethod = (typeof WS_METHODS)[number];');
lines.push('');
lines.push('export const WS_PARAMS: Record<WsMethod, MethodParams> = {');
for (const method of methods) {
  const params = contract.params[method] ?? {};
  const required = (params.required ?? []).map((name) => `'${name}'`).join(', ');
  const optional = (params.optional ?? []).map((name) => `'${name}'`).join(', ');
  lines.push(`  '${method}': { required: [${required}], optional: [${optional}] },`);
}
lines.push('};');
lines.push('');
lines.push('/** Capabilities every build provides. */');
lines.push('export const STATIC_CAPABILITIES = [');
for (const name of contract.capabilities.static) lines.push(`  '${name}',`);
lines.push('] as const;');
lines.push('');
lines.push('/**');
lines.push(' * Capabilities that depend on the assembly. `when` names the service that');
lines.push(' * provides them: a client must ask the gateway (`initialize.capabilities`)');
lines.push(' * rather than infer them, and a fixture must declare which ones it fakes.');
lines.push(' */');
lines.push('export const CONDITIONAL_CAPABILITIES = [');
for (const item of contract.capabilities.conditional) {
  lines.push(`  { name: '${item.name}', when: '${item.when}' },`);
}
lines.push('] as const;');
lines.push('');
lines.push('export const PROTOCOL_VERSION = ' + JSON.stringify(contract.protocolVersion) + ';');
lines.push('');

writeFileSync(OUTPUT, lines.join('\n'));
console.log(`gen-ws-contract: ${methods.length} methods, ` +
  `${contract.capabilities.static.length} static + ` +
  `${contract.capabilities.conditional.length} conditional capabilities → src/design/ws-contract.ts`);
