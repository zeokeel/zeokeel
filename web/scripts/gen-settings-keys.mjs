#!/usr/bin/env node
// Generate the settings-row constants the web client may use.
//
// Why this exists: `settings.set` only validates the *shape* of a key (non-empty,
// ≤128 bytes, first char alphanumeric, `[A-Za-z0-9._-]`). It has no allow-list,
// because the gateway would have to hard-code every module's keys — the coupling
// the Lead rejected. So a typo in a settings key is accepted by the gateway and
// simply never read by the backend: the user changes a setting and nothing
// happens, with no error anywhere.
//
// The gate therefore lives on this side: keys are generated from the backend's
// own constants, and `src/` may not contain a literal settings key.
//
// Sources: every `Setting*` constant in internal/contracts/*.go whose value is a
// string literal (`const SettingChatFontSize = "ui.chatFontSize"`). Keys that
// modules build by concatenation (e.g. `mcp.oauth.<server>`) are not enumerable
// and are deliberately absent.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const contractsDir = resolve(repo, 'internal/contracts');
const target = resolve(here, '../src/design/settings-keys.ts');

// const SettingFoo = "some.key"
// `const SettingX = "k"` on one line is as valid as a `Name = "k"` inside a
// const block: modelcatalog.models was missing from the generated table because
// only the block form matched.
const declaration = /^\s*(?:const\s+)?(Setting[A-Za-z0-9_]+)\s*=\s*"([^"]+)"/;

const files = readdirSync(contractsDir)
  .filter((name) => name.endsWith('.go') && !name.endsWith('_test.go'))
  .sort();

const found = new Map(); // goName -> key
const seenKeys = new Map(); // key -> goName
for (const file of files) {
  const text = readFileSync(resolve(contractsDir, file), 'utf8');
  for (const line of text.split('\n')) {
    const match = declaration.exec(line);
    if (!match) continue;
    const [, goName, key] = match;
    if (found.has(goName) && found.get(goName) !== key) {
      console.error(`gen-settings-keys: ${goName} has two values (${found.get(goName)}, ${key})`);
      process.exit(1);
    }
    found.set(goName, key);
    // Two Go names for one key is a real duplicate to look at, not a generator
    // problem: report it and keep the first so the output stays deterministic.
    if (seenKeys.has(key) && seenKeys.get(key) !== goName) {
      console.warn(`gen-settings-keys: ${key} declared by ${seenKeys.get(key)} and ${goName}`);
      continue;
    }
    seenKeys.set(key, goName);
  }
}

if (found.size === 0) {
  console.error(`gen-settings-keys: no Setting* constants found in ${contractsDir}`);
  process.exit(1);
}

const entries = [...found.entries()].sort(([a], [b]) => a.localeCompare(b));

/** camelCase a Go constant name minus the `Setting` prefix (acronyms stay whole). */
const camel = (goName) => {
  const base = goName.replace(/^Settings?/, '');
  // A leading acronym followed by a word keeps its letters together:
  // LSPServers → lspServers, NetProxy → netProxy.
  const acronym = /^([A-Z]+)([A-Z][a-z][A-Za-z0-9]*)$/.exec(base);
  if (acronym) return acronym[1].toLowerCase() + acronym[2];
  return base.charAt(0).toLowerCase() + base.slice(1);
};

const lines = [];
lines.push('// Code generated by scripts/gen-settings-keys.mjs; DO NOT EDIT.');
lines.push('//');
lines.push('// Settings row keys, copied from internal/contracts (the backend owns them).');
lines.push('// `settings.set` validates shape only, so a hand-written key would fail');
lines.push('// silently: the gateway stores it, no module ever reads it.');
lines.push('');
lines.push('/** Every enumerable settings row key the backend declares. */');
lines.push('export const SETTING_KEYS = {');
for (const [goName, key] of entries) {
  lines.push(`  /** ${goName} */`);
  lines.push(`  ${camel(goName)}: '${key}',`);
}
lines.push('} as const;');
lines.push('');
lines.push('export type SettingKey = (typeof SETTING_KEYS)[keyof typeof SETTING_KEYS];');
lines.push('');
lines.push('/** The wire keys, for validation or iteration (never for literal comparisons). */');
lines.push('export const SETTING_KEY_LIST: readonly SettingKey[] = Object.values(SETTING_KEYS);');
lines.push('');
lines.push('/** Prefixes whose real keys are built at runtime (`mcp.oauth.<server>`). */');
lines.push('export const SETTING_KEY_PREFIXES = [');
const prefixes = new Set();
for (const key of seenKeys.keys()) {
  const parts = key.split('.');
  if (parts.length >= 2) prefixes.add(`${parts[0]}.`);
}
for (const prefix of [...prefixes].sort()) lines.push(`  '${prefix}',`);
lines.push('] as const;');
lines.push('');

writeFileSync(target, `${lines.join('\n')}\n`);
console.log(
  `gen-settings-keys: wrote ${entries.length} keys to ${target.replace(`${repo}/`, '')}`,
);