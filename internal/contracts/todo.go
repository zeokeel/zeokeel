package contracts

// Todo read model.

import (
	cordis "github.com/zeokeel/zeokeel-kernel"
)

// Todo statuses, the DSH todo_write vocabulary: an item is pending, being
// worked on, or completed. The agent replaces the WHOLE list with one todo_write
// call; the UI only reads it.
const (
	// TodoStatusPending waits to start.
	TodoStatusPending = "pending"
	// TodoStatusInProgress is the item the agent is working on now.
	TodoStatusInProgress = "in_progress"
	// TodoStatusCompleted finished.
	TodoStatusCompleted = "completed"
)

// TodoItem is one item of the agent's current todo list.
type TodoItem struct {
	// ID is stable within the list (generated by the backend when the model
	// omits it).
	ID string
	// Content is what to do.
	Content string
	// Status is one of the TodoStatus* values.
	Status string
}

// TodoService is the optional read model of the agent's todo list, provided by
// the toolkit (contracts.KeyTodo) and consumed by the session's composer dock.
//
// LIMITATION (honest, not per-session): the current toolkit implementation
// exposes the rig todo store built with the toolset, which lives for the whole
// process — one list shared by every conversation, and replaced by whichever
// session last called todo_write. The contract does not claim per-session
// scoping; a future per-session store can implement this same interface without
// changing the UI, and the dock documents the current behavior.
type TodoService interface {
	// Todos returns the current list snapshot, in the agent's order (a copy: the
	// caller may not mutate the store through it).
	Todos() []TodoItem
}

// KeyTodo is provided by the toolkit module and consumed by the session composer
// dock. It is optional: a host without the toolkit shows no dock.
var KeyTodo = cordis.NewServiceKey[TodoService]("zeokeel/todo")
